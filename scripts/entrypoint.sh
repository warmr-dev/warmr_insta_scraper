#!/bin/sh
# Точка входа контейнера.
#
# Миграции НЕ запускаются автоматически. Причина конкретная: на Railway
# `alembic upgrade head` падал с "Can't locate revision identified by '0002'" -
# база уже была на 0002, а в образе этой ревизии ещё не было, и контейнер
# уходил в цикл падений.
#
# Схема меняется редко и осознанно, поэтому это ручная операция:
#
#     alembic upgrade head
#
# Установите RUN_MIGRATIONS=true, если всё же хотите миграцию при старте.
# Она не остановит запуск при ошибке: рассинхрон ревизий не должен ронять
# сбор сторис.

set -e

if [ "${RUN_MIGRATIONS}" = "true" ]; then
    echo "RUN_MIGRATIONS=true - применяю миграции"
    if alembic upgrade head; then
        echo "миграции применены"
    else
        # Не выходим: скорее всего база новее образа. Работать это не мешает.
        echo "ВНИМАНИЕ: миграция не удалась, продолжаю запуск" >&2
        echo "  проверьте: alembic current и alembic history" >&2
    fi
fi

exec "$@"
